/**
 * Where uploaded case files live. In production that's an S3 bucket; locally
 * and in tests, a folder on disk. The browser uploads straight to the store
 * with a short-lived signed URL, and downloads through another, so large files
 * never pass through the API server.
 *
 * Keys look like `uploads/<caseId>/<uuid>` (not yet confirmed),
 * `cases/<caseId>/<materialId>` or `avatars/<userId>/<uuid>` (profile
 * pictures); they never contain user-supplied text.
 */
export interface FileStorage {
  /** Where the browser should PUT the file, and the headers it must send. Valid for 15 minutes. */
  uploadTarget(key: string, contentType: string, size: number): Promise<{ url: string; headers: Record<string, string> }>
  /** The stored size in bytes, or null if there's nothing at `key`. */
  size(key: string): Promise<number | null>
  move(from: string, to: string): Promise<void>
  /** A link (valid for 5 minutes) that downloads the file as an attachment named `filename`. */
  downloadUrl(key: string, filename: string, contentType: string): Promise<string>
  /** The file's contents, read by the server (e.g. to transcribe it for the AI witnesses). */
  read(key: string): Promise<Buffer>
  /** Stores a file directly from the server (seeding, moving old files out of Postgres). */
  put(key: string, data: Buffer, contentType: string): Promise<void>
  /** Missing keys are ignored. */
  delete(keys: string[]): Promise<void>
}

export const UPLOAD_URL_TTL_SECONDS = 15 * 60
export const DOWNLOAD_URL_TTL_SECONDS = 5 * 60

/** Keys are generated by the app; anything else is refused so it can't escape the store. */
export const KEY_PATTERN = /^(uploads|cases|avatars)\/[0-9a-f-]{36}\/[0-9a-f-]{36}$/

/** `attachment; filename="…"` with an ASCII fallback and the exact UTF-8 name. */
export function attachmentHeader(filename: string) {
  const ascii = filename.replace(/[^\x20-\x7e]|["\\]/g, '_')
  const encoded = encodeURIComponent(filename).replace(/['()*]/g, (c) => `%${c.charCodeAt(0).toString(16).toUpperCase()}`)
  return `attachment; filename="${ascii}"; filename*=UTF-8''${encoded}`
}

/**
 * The largest case file accepted. Uploads go straight to storage rather than
 * through the API, so this can be well above a request-body limit.
 */
export const MAX_UPLOAD_BYTES = 100 * 1024 * 1024 // 100 MB
